"""La migration Alembic initiale s'applique et correspond exactement aux modèles ORM."""

from __future__ import annotations

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect

BACKEND = Path(__file__).resolve().parents[1]


def _config(url: str) -> Config:
    cfg = Config(str(BACKEND / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND / "alembic"))
    cfg.set_main_option("sqlalchemy.url", url)
    return cfg


def test_upgrade_puis_downgrade(tmp_path: Path) -> None:
    url = f"sqlite:///{tmp_path / 'migr.db'}"
    cfg = _config(url)
    command.upgrade(cfg, "head")

    tables = set(inspect(create_engine(url)).get_table_names())
    attendues = {
        "organisation",
        "cle_api",
        "utilisateur",
        "site",
        "destinataire_alerte",
        "moteur",
        "mesure",
        "analyse",
        "alerte",
        "retour_technicien",
    }
    assert attendues <= tables

    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - message utile en cas d'échec
        pytest.fail(f"Les modèles divergent de la migration : {exc}")

    command.downgrade(cfg, "base")
    assert set(inspect(create_engine(url)).get_table_names()) <= {"alembic_version"}
